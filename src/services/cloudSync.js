export function getSupabaseClient(url, key) {
  if (!url || !key) return null;
  if (!supabaseClient || supabaseClient.supabaseUrl !== url) {
    try {
      supabaseClient = createClient(url, key, {
        auth: { persistSession: false },
        realtime: {
          params: {
            eventsPerSecond: 10,
          },
        },
      });
    } catch (e) {
      console.error('Failed to create Supabase client:', e);
      return null;
    }
  }
  return supabaseClient;
}

// Test cloud database connection
export async function testCloudConnection(url, key) {
  try {
    const client = getSupabaseClient(url, key);
    if (!client) return { success: false, message: 'Invalid URL or Key.' };

    const { data, error } = await client.from('products').select('count', { count: 'exact', head: true });
    if (error) {
      if (error.code === '42P01') {
        return {
          success: false,
          needsSchema: true,
          message: 'Connected to Supabase! However, the database tables need to be created. Please run the SQL schema script provided.',
        };
      }
      return { success: false, message: error.message };
    }

    return { success: true, message: 'Connected successfully to Cloud Database!' };
  } catch (err) {
    return { success: false, message: err.message };
  }
}

// Push local products & customers to cloud
export async function pushLocalDataToCloud(url, key) {
  const client = getSupabaseClient(url, key);
  if (!client) throw new Error('Cloud sync is not configured.');

  // Push products
  const localProducts = await db.products.toArray();
  if (localProducts.length > 0) {
    const productsPayload = localProducts.map(p => ({
      name: p.name,
      brand: p.brand,
      category: p.category,
      gender: p.gender,
      material: p.material,
      hsn: p.hsn || '6205',
      tax_rate: p.taxRate || 5,
      description: p.description,
      variants: p.variants || [],
      updated_at: new Date().toISOString(),
    }));

    const { error: prodErr } = await client.from('products').upsert(productsPayload, { onConflict: 'name' });
    if (prodErr) console.warn('Product push warning:', prodErr);
  }

  // Push customers
  const localCustomers = await db.customers.toArray();
  if (localCustomers.length > 0) {
    const customerPayload = localCustomers.map(c => ({
      name: c.name,
      phone: c.phone,
      email: c.email || '',
      address: c.address || '',
      gstin: c.gstin || '',
      loyalty_points: Number(c.loyaltyPoints ?? c.loyalty_points) || 0,
      credit_balance: Number(c.creditBalance ?? c.credit_balance) || 0,
      total_spent: Number(c.totalSpent ?? c.total_spent) || 0,
      visit_count: Number(c.visitCount ?? c.visit_count) || 0,
      updated_at: new Date().toISOString(),
    }));

    const { error: custErr } = await client.from('customers').upsert(customerPayload, { onConflict: 'phone' });
    if (custErr) console.warn('Customer push warning:', custErr);
  }

  return { success: true, pushedProducts: localProducts.length, pushedCustomers: localCustomers.length };
}

// Pull cloud products & customers into this local device
export async function pullCloudDataToLocal(url, key) {
  const client = getSupabaseClient(url, key);
  if (!client) throw new Error('Cloud sync is not configured.');

  // Pull products
  const { data: cloudProducts, error: prodErr } = await client.from('products').select('*');
  if (prodErr) throw prodErr;

  if (cloudProducts && cloudProducts.length > 0) {
    for (const cp of cloudProducts) {
      const existing = await db.products.where('name').equals(cp.name).first();
      const productObj = {
        name: cp.name,
        brand: cp.brand,
        category: cp.category,
        gender: cp.gender,
        material: cp.material,
        hsn: cp.hsn,
        taxRate: Number(cp.tax_rate) || 5,
        description: cp.description,
        variants: cp.variants || [],
        updatedAt: cp.updated_at,
      };

      if (existing) {
        await db.products.update(existing.id, productObj);
      } else {
        await db.products.add(productObj);
      }
    }
  }

  // Pull customers
  const { data: cloudCustomers, error: custErr } = await client.from('customers').select('*');
  if (!custErr && cloudCustomers) {
    for (const cc of cloudCustomers) {
      const existing = await db.customers.where('phone').equals(cc.phone).first();
      const custObj = {
        name: cc.name,
        phone: cc.phone,
        email: cc.email,
        address: cc.address,
        gstin: cc.gstin,
        loyaltyPoints: Number(cc.loyalty_points) || 0,
        creditBalance: Number(cc.credit_balance) || 0,
        totalSpent: Number(cc.total_spent) || 0,
        visitCount: Number(cc.visit_count) || 0,
      };
      if (existing) {
        await db.customers.update(existing.id, custObj);
      } else {
        await db.customers.add(custObj);
      }
    }
  }

  return {
    success: true,
    pulledProducts: cloudProducts?.length || 0,
    pulledCustomers: cloudCustomers?.length || 0,
  };
}

