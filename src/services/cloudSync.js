// Start Realtime WebSocket listener for Multi-Counter live updates
export function initRealtimeCloudSync(url, key, onRemoteUpdate) {
  if (!url || !key) return null;
  const client = getSupabaseClient(url, key);
  if (!client) return null;

  if (realtimeSubscription) {
    realtimeSubscription.unsubscribe();
  }

  realtimeSubscription = client
    .channel('pos_realtime_channel')
    .on('postgres_changes', { event: '*', schema: 'public', table: 'products' }, async (payload) => {
      try {
        if (payload.new && payload.new.name) {
          const cp = payload.new;
          const existing = await db.products.where('name').equals(cp.name).first();
          const productObj = {
            name: cp.name,
            brand: cp.brand,
            category: cp.category,
            gender: cp.gender,
            material: cp.material,
            hsn: cp.hsn,
            taxRate: Number(cp.tax_rate) || 5,
            description: cp.description,
            variants: cp.variants || [],
            updatedAt: cp.updated_at,
          };
          if (existing) {
            await db.products.update(existing.id, productObj);
          } else {
            await db.products.add(productObj);
          }
        }
      } catch (e) {
        console.error('Error applying realtime product update:', e);
      }
      onRemoteUpdate?.('products', payload);
    })
    .on('postgres_changes', { event: '*', schema: 'public', table: 'sales' }, async (payload) => {
      try {
        if (payload.new && payload.new.invoice_no) {
          const cs = payload.new;
          const existing = await db.sales.where('invoiceNo').equals(cs.invoice_no).first();
          const saleObj = {
            invoiceNo: cs.invoice_no,
            date: cs.date,
            counterName: cs.counter_name,
            customerName: cs.customer_name,
            customerPhone: cs.customer_phone,
            customerGstin: cs.customer_gstin,
            items: cs.items || [],
            subtotal: Number(cs.subtotal) || 0,
            taxableSubtotal: Number(cs.taxable_subtotal) || 0,
            totalCGST: Number(cs.total_cgst) || 0,
            totalSGST: Number(cs.total_sgst) || 0,
            totalIGST: Number(cs.total_igst) || 0,
            totalTax: Number(cs.total_tax) || 0,
            billDiscount: Number(cs.bill_discount) || 0,
            roundOff: Number(cs.round_off) || 0,
            netTotal: Number(cs.net_total) || 0,
            paymentMethod: cs.payment_method,
            paymentDetails: cs.payment_details,
            tenderedAmount: Number(cs.tendered_amount) || 0,
            changeAmount: Number(cs.change_amount) || 0,
            loyaltyPointsEarned: Number(cs.loyalty_points_earned) || 0,
            loyaltyPointsRedeemed: Number(cs.loyalty_points_redeemed) || 0,
            status: cs.status || 'completed',
          };
          if (existing) {
            await db.sales.update(existing.id, saleObj);
          } else {
            await db.sales.add(saleObj);
          }
          console.log('Real-time sale updated locally:', cs.invoice_no);
        }
      } catch (e) {
        console.error('Error applying realtime sales update:', e);
      }
      onRemoteUpdate?.('sales', payload);
    })
    .on('postgres_changes', { event: '*', schema: 'public', table: 'customers' }, async (payload) => {
      try {
        if (payload.new && payload.new.phone) {
          const cc = payload.new;
          const existing = await db.customers.where('phone').equals(cc.phone).first();
          const custObj = {
            name: cc.name,
            phone: cc.phone,
            email: cc.email,
            address: cc.address,
            gstin: cc.gstin,
            loyaltyPoints: Number(cc.loyalty_points) || 0,
            creditBalance: Number(cc.credit_balance) || 0,
            totalSpent: Number(cc.total_spent) || 0,
            visitCount: Number(cc.visit_count) || 0,
          };
          if (existing) {
            await db.customers.update(existing.id, custObj);
          } else {
            await db.customers.add(custObj);
          }
          console.log('Real-time customer updated locally:', cc.phone);
        }
      } catch (e) {
        console.error('Error applying realtime customer update:', e);
      }
      onRemoteUpdate?.('customers', payload);
    })
    .subscribe((status) => {
      console.log('Supabase Realtime Sync Status:', status);
    });

  return realtimeSubscription;
}
